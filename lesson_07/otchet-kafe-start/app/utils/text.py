"""Утилиты для нормализации и обработки текстовых данных."""

def _squash_spaces(value: str) -> str:
    """Заменяет множественные пробелы на одиночные.

    Args:
        value: Исходная строка для обработки.

    Returns:
        Строка, в которой все последовательности пробелов заменены на один пробел.
    """    
    return " ".join(value.split())


def normalize_name(name: str) -> str:
    """Нормализует имя: убирает лишние пробелы.

    Args:
        name: Исходное имя, которое нужно привести в порядок.

    Returns:
        Отформатированное имя с заглавными первыми буквами слов.
    """    
    return _squash_spaces(name).title()
